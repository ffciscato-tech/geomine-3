import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context=vm.createContext({});
vm.runInContext(fs.readFileSync(new URL('../src/modules/cartography/line-arrows.js',import.meta.url),'utf8'),context);
const api=context.GeoMineLineArrows,plain=v=>JSON.parse(JSON.stringify(v));
assert.deepEqual(plain(api.style()),{arrowEnd:'none',arrowSize:3});
assert.deepEqual(plain(api.style({}, {arrowEnd:'filled',arrowSize:5})),{arrowEnd:'filled',arrowSize:5});
assert.equal(api.style({arrowEnd:'none'},{arrowEnd:'filled'}).arrowEnd,'none');
assert.equal(api.style({arrowEnd:'script',arrowSize:Infinity}).arrowEnd,'none');
assert.equal(api.style({arrowSize:900}).arrowSize,20);
const ring=[[1,2],[8,12],[8,12],[8,12]],before=JSON.stringify(ring),terminal=api.terminal(ring);
assert.deepEqual(plain(terminal),{a:[1,2],b:[8,12],previous:0,end:3});
assert.equal(JSON.stringify(ring),before);
assert.equal(api.terminal([[1,1],[1,1]]),null);
assert.equal(api.terminal([[1,1],[NaN,3]]),null);
assert.equal(api.terminal([[1,1],[NaN,3],[4,5]]),null,'do not draw across an invalid last segment');
assert.deepEqual(plain(api.head([0,0],[10,0],3)),[[7,1.26],[10,0],[7,-1.26]]);
assert.deepEqual(plain(api.head([10,0],[0,0],3)),[[3,-1.26],[0,0],[3,1.26]]);
assert.deepEqual(plain(api.rings([[[0,0],[1,1]],[[2,2],[3,3]]])).map(r=>plain(api.terminal(r).b)),[[1,1],[3,3]]);
const filled=api.svg([0,0],[10,0],{arrowEnd:'filled',arrowSize:3},'#123456',.3);
assert.match(filled,/data-gm-line-arrow="filled"/);assert.match(filled,/L10 0/);assert.match(filled,/ Z"/);
assert.match(api.svg([0,0],[10,0],{arrowEnd:'open'},'#123456',.3),/fill="none"/);
assert.equal(api.svg([0,0],[10,0],{arrowEnd:'open'},'#123456',0),'');
assert.equal(api.svg([0,0],[10,0],{arrowEnd:'none'},'#123456',1),'');
assert.equal(api.svg([0,0],[10,0],{arrowEnd:'filled'},'#123456',.3,1,[0,0,9,10]),'','no head at a clipped viewport endpoint');
assert.ok(!api.svg([0,0],[10,0],{arrowEnd:'filled'},'" onload="alert(1)',.3).includes(' onload="'));
console.log('PASS line arrows: inherited styles, exact endpoints, tail duplicates, multipart, no mutation, invalid geometry, reversal, viewport clipping, zero weight and SVG escaping.');

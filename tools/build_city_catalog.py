"""Generate offline navigation data. Read-only IBGE GPKG, PROJ DB and Natural Earth SHP inputs."""
import argparse
import json
import sqlite3
import struct
from pathlib import Path

p = argparse.ArgumentParser()
for name in ('ibge', 'proj', 'outline'):
    p.add_argument('--' + name, required=True)
a = p.parse_args()
def connect(path):
    return sqlite3.connect('file:' + str(Path(path).resolve()) + '?mode=ro', uri=True)
db = connect(a.ibge)
rows = db.execute("SELECT CD_MUN, trim(NM_MUN), SIGLA_UF, LAT_LOCALIDADE, LONG_LOCALIDADE FROM BR_localidades_2022 WHERE CT_LOCALIDADE='Cidade' ORDER BY CASE WHEN SCT_LOCALIDADE='Sede Municipal' THEN 1 ELSE 0 END, CD_LOCALIDADE").fetchall()
cities = {}
for code, name, uf, lat, lon in rows:
    assert -90 <= lat <= 90 and -180 <= lon <= 180
    cities.setdefault(code, [code, name, uf, round(lat, 6), round(lon, 6)])
assert len(cities) == 5570, 'Unexpected IBGE edition or missing municipal seats'
db.close()
db = connect(a.proj)
codes = {4326, 4674, 4618, 3857, 29101}
for base, first, last in ((31960,18,25),(31954,18,22),(29170,18,25),(22500,18,25),(32600,1,60),(32700,1,60)):
    codes.update(base + z for z in range(first, last + 1))
areas = {}
for table in ('projected_crs', 'geodetic_crs'):
    query = f"SELECT c.code,c.name,e.name,e.south_lat,e.west_lon,e.north_lat,e.east_lon FROM {table} c JOIN usage u ON u.object_table_name=? AND u.object_auth_name=c.auth_name AND u.object_code=c.code JOIN extent e ON e.auth_name=u.extent_auth_name AND e.code=u.extent_code WHERE c.auth_name='EPSG' ORDER BY c.code,e.code"
    for code, name, desc, south, west, north, east in db.execute(query, (table,)):
        if int(code) in codes and None not in (south, west, north, east):
            areas.setdefault('EPSG:' + str(code), {'name': name, 'description': desc, 'bounds': [south, west, north, east]})
metadata = dict(db.execute('SELECT key,value FROM metadata'))
db.close()
# Outline lines only: do not imply legal boundaries or polygon topology.
rings = []
with open(a.outline, 'rb') as f:
    assert struct.unpack_from('<i', f.read(100), 32)[0] == 5
    while record := f.read(8):
        size = struct.unpack('>ii', record)[1] * 2
        body = f.read(size)
        assert len(body) == size
        if struct.unpack_from('<i', body)[0] == 0:
            continue
        assert struct.unpack_from('<i', body)[0] == 5
        parts, count = struct.unpack_from('<ii', body, 36)
        starts = list(struct.unpack_from('<' + 'i' * parts, body, 44)) + [count]
        pts = [tuple(round(v, 3) for v in struct.unpack_from('<dd', body, 44 + 4 * parts + 16 * i)) for i in range(count)]
        rings.extend(pts[starts[i]:starts[i+1]] for i in range(parts))
data = {'edition': 'IBGE · Localidades do Brasil 2022', 'epsgEdition': metadata['EPSG.VERSION'], 'cities': sorted(cities.values(), key=lambda x: (x[1], x[2])), 'areas': areas, 'outline': {'type': 'MultiLineString', 'coordinates': rings}}
out = Path(__file__).resolve().parents[1] / 'src/modules/cartography/city-catalog.js'
out.write_text('// Generated by tools/build_city_catalog.py; provenance: docs/crs-city-navigation.md\nwindow.GeoMineCityCatalog=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/') + ';\n', encoding='utf-8')
print(f'{len(cities)} cities; {len(areas)} EPSG areas; {out.stat().st_size} bytes')
